def format_html_report(report: AuditReport) -> str:
    """Render an AuditReport as a self-contained HTML string."""
    ts = report.audit_timestamp
    ts_str = ts.strftime("%Y-%m-%d %H:%M:%S UTC") if ts else "N/A"

    filters_parts: list[str] = []
    fa = report.filters_applied
    if fa.path_prefix:
        filters_parts.append(f"path={html.escape(fa.path_prefix)}")
    if fa.name_pattern:
        filters_parts.append(f"name={html.escape(fa.name_pattern)}")
    if fa.tags:
        for k, v in fa.tags.items():
            filters_parts.append(f"tag {html.escape(k)}={html.escape(v)}")
    filters_str = ", ".join(filters_parts) if filters_parts else "none"

    summary_badges = _render_summary_badges(report.summary)

    by_category: dict[str, list[Finding]] = {}
    for f in report.findings:
        by_category.setdefault(f.category.value, []).append(f)

    sections: list[str] = []
    if report.findings:
        for cat in CATEGORY_ORDER:
            if cat in by_category:
                sections.append(
                    _render_findings_table(by_category[cat], cat)
                )
    else:
        sections.append('<div class="no-issues">No issues found.</div>')

    if report.data_gaps:
        sections.append(_render_data_gaps(report.data_gaps))

    return _PAGE_TEMPLATE.substitute(
        account_id=html.escape(report.account_id),
        threshold_days=report.threshold_days,
        timestamp=html.escape(ts_str),
        summary_badges=summary_badges,
        content="\n".join(sections),
        filters=filters_str,
        aws_managed="yes" if report.include_aws_managed else "no",
    )


def _render_summary_badges(summary: ReportSummary) -> str:
    """Render the severity and category count badge row."""
    parts = [
        '<div class="badges">',
        f'  <span class="badge badge-total">Total: '
        f"{summary.total_findings}"
        f"</span>",
    ]
    for sev_key in ("critical", "high", "medium", "low"):
        count = summary.by_severity.get(sev_key, 0)
        label = sev_key.title()
        parts.append(
            f'  <span class="badge badge-{sev_key}">'
            f"{label}: {count}</span>"
        )
    for cat in CATEGORY_ORDER:
        count = summary.by_category.get(cat, 0)
        label = CATEGORY_DISPLAY.get(cat, cat)
        parts.append(
            f'  <span class="badge badge-category">'
            f"{html.escape(label)}: {count}</span>"
        )
    parts.append("</div>")
    return "\n".join(parts)


def _render_findings_table(findings: list[Finding], category: str) -> str:
    """Render a single category's findings as an HTML table."""
    display_name = CATEGORY_DISPLAY.get(category, category)
    rows: list[str] = []
    for f in findings:
        sev_val = f.severity.value
        sev_label = sev_val.title()
        sev_color = SEVERITY_COLORS.get(sev_val, "#6c757d")
        extra_cls = " sev-medium" if sev_val == "medium" else ""
        rows.append(
            "<tr>"
            "<td>"
            f"<strong>{html.escape(f.principal_name)}</strong><br>"
            f'<span class="principal-arn">'
            f"{html.escape(f.principal_arn)}</span>"
            "</td>"
            f'<td><span class="sev-badge{extra_cls}" '
            f'style="background:{sev_color}">'
            f"{sev_label}</span></td>"
            f"<td>{html.escape(f.title)}</td>"
            f"<td>{html.escape(f.recommendation)}</td>"
            "</tr>"
        )
    return (
        "<details>\n"
        f"  <summary>{html.escape(display_name)} ({len(findings)})</summary>\n"
        "  <table>\n"
        "    <thead><tr>"
        "<th>Principal</th><th>Severity</th>"
        "<th>Title</th><th>Recommendation</th>"
        "</tr></thead>\n"
        "    <tbody>\n"
        "      " + "\n      ".join(rows) + "\n"
        "    </tbody>\n"
        "  </table>\n"
        "</details>"
    )


def _render_data_gaps(data_gaps: list[DataGap]) -> str:
    """Render the data gaps section as an HTML table."""
    rows: list[str] = []
    for g in data_gaps:
        rows.append(
            f"<tr><td>{html.escape(g.principal_arn)}</td>"
            f"<td>{html.escape(g.reason)}</td></tr>"
        )
    return (
        "<details>\n"
        f"  <summary>Data Gaps ({len(data_gaps)})</summary>\n"
        "  <table>\n"
        "    <thead><tr>"
        "<th>Principal ARN</th><th>Reason</th>"
        "</tr></thead>\n"
        "    <tbody>\n"
        "      " + "\n      ".join(rows) + "\n"
        "    </tbody>\n"
        "  </table>\n"
        "</details>"
    )
